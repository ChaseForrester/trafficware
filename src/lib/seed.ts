function skill(name: string, expires: string, document: string): SkillRecord {
    return { id: uid('sk'), name, expires, document }
}

function prior(today: string, daysAgo: number[], hours: number) {
    return daysAgo.map((days) => ({ date: addDays(today, -days), hours }))
}

function slot(role: string, personId: string | null = null, response: 'pending' | 'accepted' | null = null) {
    return { id: uid('slot'), role, personId, response: personId ? response ?? 'pending' : null }
}

function docket(
    bookingId: string,
    personId: string,
    start: string,
    end: string,
    status: Docket['status'],
    extra: Partial<Docket> = {},
): Docket {
    return {
        id: uid('doc'),
        bookingId,
        personId,
        start,
        end,
        breakMins: 30,
        notes: '',
        signedBy: '',
        nearMiss: '',
        photoName: '',
        status,
        submittedAt: new Date().toISOString(),
        queryNote: '',
        siteCheck: null,
        ...extra,
    }
}

